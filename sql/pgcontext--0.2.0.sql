CREATE FUNCTION pgcontext._publish_generation(target_generation bigint)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    target_collection bigint;
    target_alias text;
    previous_generation bigint;
BEGIN
    SELECT collection_id, publication_alias
      INTO target_collection, target_alias
      FROM pgcontext._generation_manifests
     WHERE generation = target_generation
       AND lifecycle_state IN ('validated', 'published')
       AND validation_passed
     FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'generation % is not validated for publication', target_generation
            USING ERRCODE = '55000';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pgcontext._generation_artifacts WHERE generation = target_generation
    ) THEN
        RAISE EXCEPTION 'generation % has no artifact inventory', target_generation
            USING ERRCODE = '55000';
    END IF;

    -- A collection row always exists for a valid manifest and provides a
    -- transaction-scoped serialization point even when an alias has never
    -- been published before.
    PERFORM 1
      FROM pgcontext._collections
     WHERE collection_id = target_collection
     FOR UPDATE;

    SELECT generation
      INTO previous_generation
      FROM pgcontext._generation_aliases
     WHERE collection_id = target_collection
       AND publication_alias = target_alias
     FOR UPDATE;

    IF previous_generation IS NOT NULL AND previous_generation <> target_generation THEN
        DELETE FROM pgcontext._generation_reader_pins AS pins
         WHERE pins.generation = previous_generation
           AND NOT EXISTS (
               SELECT 1
                 FROM pg_catalog.pg_stat_activity AS activity
                WHERE activity.pid = pins.backend_pid
                  AND pg_catalog.to_char(
                          activity.backend_start AT TIME ZONE 'UTC',
                          'YYYY-MM-DD"T"HH24:MI:SS.US'
                      ) = pins.backend_identity
           );
        UPDATE pgcontext._generation_manifests
           SET lifecycle_state = CASE
                   WHEN EXISTS (
                       SELECT 1
                         FROM pgcontext._generation_reader_pins AS pins
                        WHERE pins.generation = previous_generation
                   ) THEN 'retiring'
                   ELSE 'retired'
               END,
               updated_at = pg_catalog.now()
         WHERE generation = previous_generation
           AND lifecycle_state = 'published';
    END IF;

    INSERT INTO pgcontext._generation_aliases (collection_id, publication_alias, generation)
    VALUES (target_collection, target_alias, target_generation)
    ON CONFLICT (collection_id, publication_alias) DO UPDATE
       SET generation = EXCLUDED.generation,
           updated_at = pg_catalog.now();

    UPDATE pgcontext._generation_manifests
       SET lifecycle_state = 'published', updated_at = pg_catalog.now()
     WHERE generation = target_generation;
END;
$$;

CREATE FUNCTION pgcontext._pin_generation(
    target_collection bigint,
    target_alias text
)
RETURNS bigint
LANGUAGE plpgsql
AS $$
DECLARE
    target_generation bigint;
    backend_identity_value text;
BEGIN
    SELECT aliases.generation
      INTO target_generation
      FROM pgcontext._generation_aliases AS aliases
      JOIN pgcontext._generation_manifests AS manifests USING (generation)
     WHERE aliases.collection_id = target_collection
       AND aliases.publication_alias = target_alias
       AND manifests.lifecycle_state = 'published'
     FOR SHARE OF aliases, manifests;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;
    SELECT pg_catalog.to_char(
               activity.backend_start AT TIME ZONE 'UTC',
               'YYYY-MM-DD"T"HH24:MI:SS.US'
           )
      INTO STRICT backend_identity_value
      FROM pg_catalog.pg_stat_activity AS activity
     WHERE activity.pid = pg_catalog.pg_backend_pid();
    INSERT INTO pgcontext._generation_reader_pins (
        generation, backend_pid, backend_identity, pin_count
    )
    VALUES (
        target_generation, pg_catalog.pg_backend_pid(), backend_identity_value, 1
    )
    ON CONFLICT (generation, backend_pid, backend_identity) DO UPDATE
       SET pin_count = pgcontext._generation_reader_pins.pin_count + 1,
           updated_at = pg_catalog.now();
    RETURN target_generation;
END;
$$;

CREATE FUNCTION pgcontext._unpin_generation(target_generation bigint)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    backend_identity_value text;
BEGIN
    SELECT pg_catalog.to_char(
               activity.backend_start AT TIME ZONE 'UTC',
               'YYYY-MM-DD"T"HH24:MI:SS.US'
           )
      INTO STRICT backend_identity_value
      FROM pg_catalog.pg_stat_activity AS activity
     WHERE activity.pid = pg_catalog.pg_backend_pid();
    UPDATE pgcontext._generation_reader_pins
       SET pin_count = pin_count - 1,
           updated_at = pg_catalog.now()
     WHERE generation = target_generation
       AND backend_pid = pg_catalog.pg_backend_pid()
       AND backend_identity = backend_identity_value
       AND pin_count > 1;
    IF NOT FOUND THEN
        DELETE FROM pgcontext._generation_reader_pins
         WHERE generation = target_generation
           AND backend_pid = pg_catalog.pg_backend_pid()
           AND backend_identity = backend_identity_value;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'generation % is not pinned by this backend', target_generation
                USING ERRCODE = '55000';
        END IF;
    END IF;
    UPDATE pgcontext._generation_manifests AS manifests
       SET lifecycle_state = 'retired', updated_at = pg_catalog.now()
     WHERE manifests.generation = target_generation
       AND manifests.lifecycle_state = 'retiring'
       AND NOT EXISTS (
           SELECT 1
             FROM pgcontext._generation_reader_pins AS pins
            WHERE pins.generation = manifests.generation
       );
END;
$$;

